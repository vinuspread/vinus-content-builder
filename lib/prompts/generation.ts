export function buildGenerationUserPrompt(
  contentTypeName: string,
  title: string,
  caption: string,
  keywords: string[],
  sourceUrl: string
): string {
  return `다음 수집 콘텐츠를 바탕으로 바이너스 SNS 카드뉴스 원고를 작성해주세요.

콘텐츠 유형: ${contentTypeName}
원본 제목: ${title}
핵심 키워드: ${keywords.join(', ')}
원본 요약: ${caption.slice(0, 800)}
출처: ${sourceUrl}

위 내용을 바탕으로, 바이너스의 톤과 기준에 맞게 독자적인 카드뉴스 원고를 작성하세요.
원본을 그대로 번역하거나 요약하지 말고, 바이너스 독자(중소기업·스타트업 실무자)에게 맞게 재해석하세요.`;
}
